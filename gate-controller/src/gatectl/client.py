"""API client for the gate endpoints: timeouts, retries with exponential backoff + jitter, idempotency keys.

Rules (docs/02-architecture.md §10):
- every request has a timeout (2 s): a driver is waiting, and a hung request must not freeze the lane;
- retries only for failures that might succeed next time (network error, timeout, 5xx, 429), up to 3, with backoff
  0.2 s * 2^attempt +- jitter. Jitter spreads retries out so that 200 lanes recovering from the same outage don't all
  hit the server in the same millisecond (the "thundering herd");
- retrying is SAFE because every action carries the same idempotency key (scan_id / request_id) on every attempt:
  the server returns its stored answer instead of acting twice. The key is generated by the caller (machine.py),
  once per action, never per attempt.
"""

import asyncio
import random
import uuid
from dataclasses import dataclass, field
from typing import Any

import httpx

RETRYABLE_STATUS = {429, 500, 502, 503, 504}


class GateApiError(Exception):
    """The server answered, but with an error that retrying won't fix (4xx)."""

    def __init__(self, status: int, body: dict[str, Any]) -> None:
        super().__init__(f"{status}: {body.get('code') or body}")
        self.status = status
        self.code = str(body.get("code", ""))
        self.body = body


class GateApiUnavailable(Exception):
    """No usable answer after all retries (network down, timeouts, 5xx). The caller decides what the lane shows."""


@dataclass
class RetryPolicy:
    attempts: int = 4  # 1 try + 3 retries
    base_delay: float = 0.2
    jitter: float = 0.5  # +-50 %
    rng: random.Random = field(default_factory=random.Random)

    def delay(self, attempt: int) -> float:
        backoff = self.base_delay * 2**attempt
        return float(backoff * (1 + self.rng.uniform(-self.jitter, self.jitter)))


def new_action_id() -> str:
    """One per driver action (a scan, a button press, a card tap). Reused for every retry of that action."""
    return str(uuid.uuid4())


class GateClient:
    def __init__(
        self,
        base_url: str,
        api_key: str,
        *,
        timeout: float = 2.0,
        retry: RetryPolicy | None = None,
        transport: httpx.AsyncBaseTransport | None = None,
    ) -> None:
        self._http = httpx.AsyncClient(
            base_url=base_url.rstrip("/"),
            headers={"Authorization": f"Device {api_key}"},
            timeout=timeout,
            transport=transport,
        )
        self.retry = retry or RetryPolicy()

    async def aclose(self) -> None:
        await self._http.aclose()

    async def _post(self, path: str, body: dict[str, Any] | None = None) -> dict[str, Any]:
        last_error: Exception | None = None
        for attempt in range(self.retry.attempts):
            if attempt:
                await asyncio.sleep(self.retry.delay(attempt - 1))
            try:
                response = await self._http.post(path, json=body or {})
            except httpx.TransportError as exc:  # connection refused/reset, timeouts, DNS...
                last_error = exc
                continue
            if response.status_code in RETRYABLE_STATUS:
                last_error = GateApiError(response.status_code, _json(response))
                continue
            if response.status_code >= 400:
                raise GateApiError(response.status_code, _json(response))
            return _json(response)
        raise GateApiUnavailable(f"{path}: no answer after {self.retry.attempts} attempts ({last_error!r})")

    # --- endpoints ---

    async def entry_scan(self, scan_id: str, ticket_code: str) -> dict[str, Any]:
        return await self._post("/gate/v1/entry/scan", {"scan_id": scan_id, "ticket_code": ticket_code})

    async def entry_issue(self, request_id: str) -> dict[str, Any]:
        return await self._post("/gate/v1/entry/issue", {"request_id": request_id})

    async def exit_scan(self, scan_id: str, ticket_code: str) -> dict[str, Any]:
        return await self._post("/gate/v1/exit/scan", {"scan_id": scan_id, "ticket_code": ticket_code})

    async def exit_pay(self, request_id: str, passage_id: str, card_token: str) -> dict[str, Any]:
        return await self._post(
            "/gate/v1/exit/pay", {"request_id": request_id, "passage_id": passage_id, "card_token": card_token}
        )

    async def complete(self, passage_id: str) -> dict[str, Any]:
        return await self._post(f"/gate/v1/passages/{passage_id}/complete")

    async def abort(self, passage_id: str) -> dict[str, Any]:
        return await self._post(f"/gate/v1/passages/{passage_id}/abort")

    async def heartbeat(self, firmware_version: str, printer_status: str | None) -> dict[str, Any]:
        return await self._post(
            "/gate/v1/heartbeat", {"firmware_version": firmware_version, "printer_status": printer_status}
        )

    async def ack(self, command_id: str) -> None:
        await self._post(f"/gate/v1/commands/{command_id}/ack")


def _json(response: httpx.Response) -> dict[str, Any]:
    if response.status_code == 204 or not response.content:
        return {}
    try:
        data = response.json()
    except ValueError:
        return {"raw": response.text[:200]}
    return data if isinstance(data, dict) else {"data": data}
